#!/usr/bin/env python3
"""The planet's ground: writes src/gen/planetmap.asm.

The surface is 128 characters (1024 pixels, 6.4 screens) round and wraps.
One character row (zone 10), its surface rising and falling over three
levels (its top line 0, 4 or 8 lines down) with slopes between, a column
(8 pixels) each. Towers stand every 16 columns from column 8: those columns
are flat at level 0, so each 16-column stretch between towers starts and
ends at 0.

  pl_map    the row, 128 + 21 wide (the first 21 columns again at the end,
            so a 21-column window reads straight through the wrap); codes
            are glyph * 2 (doublewide); plotmap's map width is 149
  pl_hd     each column's depth at its left edge (0, 4, 8)
  pl_hs     its slope across it: 0 flat, 1 down (+4 by its right edge),
            $FF up (-4)
"""
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COLS, VIEW = 128, 21
T_FLAT0, T_FLAT4, T_FLAT8, T_DOWN0, T_DOWN4, T_UP4, T_UP8, T_ROCK0 = range(64, 72)
FLAT = {0: T_FLAT0, 4: T_FLAT4, 8: T_FLAT8}
DOWN = {0: T_DOWN0, 4: T_DOWN4}         # from this depth down a level
UP = {4: T_UP4, 8: T_UP8}               # from this depth up a level


def stretch(rng, n):
    """n columns from level 0 back to level 0: (depth, slope) for each."""
    out, d = [], 0
    while len(out) < n:
        left = n - len(out)
        need = d // 4                     # slope columns needed to get back up
        if need >= left:                  # must head home now
            out.append((d, -1))
            d -= 4
            continue
        k = rng.random()
        if k < 0.25 and d < 8 and need + 2 < left:
            out.append((d, 1))
            d += 4
        elif k < 0.45 and d > 0:
            out.append((d, -1))
            d -= 4
        else:
            out.append((d, 0))
    assert d == 0, d
    return out


def main():
    rng = random.Random(7800)
    cols = []
    for t in range(COLS // 16):
        cols.append((0, 0))               # under a tower (column 8 + 16 t, after the shift)
        cols += stretch(rng, 15)
    cols = cols[-8:] + cols[:-8]          # towers at columns 8, 24, ... (x 64 + 128 t)
    row, hd, hs = [], [], []
    for d, sl in cols:
        if sl == 0:
            tile = FLAT[d] if not (d == 0 and rng.random() < 0.15) else T_ROCK0
        elif sl > 0:
            tile = DOWN[d]
        else:
            tile = UP[d]
        row.append(tile)
        hd.append(d)
        hs.append({0: 0, 1: 1, -1: 255}[sl])
    for t in range(COLS // 16):           # tower columns: flat at 0, no stone
        row[8 + 16 * t] = T_FLAT0
    out = ["; Generated by tools/planet.py. Do not edit.", "",
           f"PL_MAPW = {COLS + VIEW}   ; plotmap's map width", "pl_map"]
    full = row + row[:VIEW]
    for i in range(0, len(full), 25):
        out.append("    .byte " + ",".join(str(c * 2) for c in full[i:i + 25]))
    for name, tab in (("pl_hd", hd), ("pl_hs", hs)):
        out.append(name)
        for i in range(0, COLS, 32):
            out.append("    .byte " + ",".join(str(v) for v in tab[i:i + 32]))
    (ROOT / "src" / "gen").mkdir(parents=True, exist_ok=True)
    (ROOT / "src" / "gen" / "planetmap.asm").write_text("\n".join(out) + "\n")
    print("planet: " + "".join(".-_"[d // 4] for d in hd[:64]))


if __name__ == "__main__":
    main()
