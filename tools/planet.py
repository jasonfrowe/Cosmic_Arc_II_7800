#!/usr/bin/env python3
"""The planet's ground: writes src/gen/planetmap.asm.

The surface is 128 characters (1024 pixels, 6.4 screens) round and wraps.
One row (zone 10): grass along its top, soil under (tools/gfx.py's
T_GRASS tiles). It's stored 128 + 21 wide: the first 21 columns again at the
end, so any 21-column window (what a screen shows, with the fine scroll)
reads straight through, wrap or not; plotmap's map width is 149. Character
codes are (glyph) * 2 (doublewide).
"""
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COLS, VIEW = 128, 21
T_GRASS1, T_GRASS2, T_GRASS3 = range(64, 67)


def main():
    rng = random.Random(7800)
    row = [rng.choice((T_GRASS1, T_GRASS2, T_GRASS3)) for _ in range(COLS)]
    out = ["; Generated by tools/planet.py. Do not edit.", "",
           f"PL_MAPW = {COLS + VIEW}   ; plotmap's map width", "pl_map"]
    full = row + row[:VIEW]
    for i in range(0, len(full), 25):
        out.append("    .byte " + ",".join(str(c * 2) for c in full[i:i + 25]))
    (ROOT / "src" / "gen").mkdir(parents=True, exist_ok=True)
    (ROOT / "src" / "gen" / "planetmap.asm").write_text("\n".join(out) + "\n")
    print(f"planet: 1 row of {COLS + VIEW}")


if __name__ == "__main__":
    main()
