#!/usr/bin/env python3
"""The planet's terrain map: writes src/gen/planetmap.asm.

The surface is 128 characters (1024 pixels, 6.4 screens) round and wraps.
Two rows: the horizon (hills; the ground's surface at lines 12-13 of the
row) and the soil. Each row is stored 128 + 21 wide: the first 21 columns
again at the end, so any 21-column window (what a screen shows, with the
fine scroll) reads straight through, wrap or not; plotmap's map width is
149. Character codes are (glyph) * 2 (doublewide); the terrain glyphs follow
the font (tools/gfx.py: T_FLAT = 64 ...).
"""
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COLS, VIEW = 128, 21
T_FLAT, T_HILL_L, T_HILL_M, T_HILL_R, T_ROCKS, T_DIRT1, T_DIRT2, T_DIRT3 = range(64, 72)


def horizon(rng):
    row = []
    while len(row) < COLS:
        k = rng.random()
        if k < 0.35:
            row += [T_HILL_L] + [T_HILL_M] * rng.randint(0, 3) + [T_HILL_R]
        elif k < 0.5:
            row.append(T_ROCKS)
        else:
            row += [T_FLAT] * rng.randint(1, 4)
    row = row[:COLS]
    if row[-1] in (T_HILL_L, T_HILL_M):     # don't leave a hill open at the seam
        row[-1] = T_HILL_R
    if row[0] in (T_HILL_M, T_HILL_R):
        row[0] = T_HILL_L
    return row


def main():
    rng = random.Random(7800)
    rows = [horizon(rng), [rng.choice((T_DIRT1, T_DIRT2, T_DIRT3)) for _ in range(COLS)]]
    out = ["; Generated by tools/planet.py. Do not edit.", "",
           f"PL_MAPW = {COLS + VIEW}   ; plotmap's map width", "pl_map"]
    for row in rows:
        full = row + row[:VIEW]
        for i in range(0, len(full), 25):
            out.append("    .byte " + ",".join(str(c * 2) for c in full[i:i + 25]))
    (ROOT / "src" / "gen").mkdir(parents=True, exist_ok=True)
    (ROOT / "src" / "gen" / "planetmap.asm").write_text("\n".join(out) + "\n")
    print(f"planet: {len(rows)} rows of {COLS + VIEW}")


if __name__ == "__main__":
    main()
